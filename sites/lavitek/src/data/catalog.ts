export const directionBySlug: Record<string, Direction> = Object.fromEntries(
  directions.map((d) => [d.slug, d]),
)

export function findItem(dirSlug: string, itemSlug: string) {
  const dir = directionBySlug[dirSlug]
  if (!dir) return null
  const item = dir.items.find((i) => i.slug === itemSlug)
  return item ? { dir, item } : null
}
