import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const D = JSON.parse(readFileSync('data/tables.json', 'utf8'));
const tbl = id => D.tables.find(t => t.id === id);

// ─── форматирование по русской норме ─────────────────────────────────────
const dec = s => String(s).replace(/(\d)\.(\d)/g, '$1,$2');          // 0.40 → 0,40
const dim = s => dec(String(s).replace(/[*x]/g, '×'));                // 28*15 → 28×15
// Углы, где разделитель между двумя значениями отсутствует в исходнике (TODO-03/04).
const AMBIG_ANGLE = { 2419: '24 ? 19', 1924: '19 ? 24' };
const ang = s => {
  if (s === '') return '<span class="empty" title="в оригинале ячейка пустая">—</span>';
  if (AMBIG_ANGLE[s]) {
    return `<span class="flag" title="в исходнике два числа слитно, разделитель не читается">${AMBIG_ANGLE[s]}</span>`;
  }
  return dec(String(s).replace(/或/g, ' или ').replace(/（/g, ' (').replace(/）/g, ')'));
};
const spec = s => dim(String(s).replace(/9\*7钢套：/, 'обойма 9×7: '));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const holes = arr => arr.length
  ? arr.map(v => `<span class="v">${esc(dec(v))}</span>`).join('')
  : '<span class="empty">—</span>';

