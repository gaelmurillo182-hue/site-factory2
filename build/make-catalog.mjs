function diaChart() {
  const pc = v => (v / DIA_MAX * 100).toFixed(2) + '%';
  const rows = DIA.map(([g, a, b, use], i) => `
    <div class="dia-row${i % 2 ? ' z' : ''}">
      <span class="dia-g">${g}</span>
      <span class="dia-track"><i style="left:${pc(a)};width:${pc(b - a)}"></i></span>
      <span class="dia-n">${dec(String(a.toFixed(1)))}–${dec(String(b.toFixed(1)))}</span>
      <span class="dia-u">${use}</span>
    </div>`).join('');
  const ticks = [0, 5, 10, 15, 20, 25].map(t =>
    `<span style="left:${pc(t)}">${t}</span>`).join('');
  return `
  <div class="dia">
    <div class="dia-head">
      <span class="dia-g">Марка</span>
      <span class="dia-track"><span class="dia-axis">${ticks}</span></span>
      <span class="dia-n">Ø, мм</span>
      <span class="dia-u">Применение</span>
    </div>
    ${rows}
  </div>`;
}

