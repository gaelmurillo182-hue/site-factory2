// ─── таблица типоразмеров ────────────────────────────────────────────────
function sizeTable(id, opts = {}) {
  const t = tbl(id);
  const angH = opts.angleHeader || 'Угол рабочего конуса 2α';
  const rows = t.rows.map((r, i) => `
      <tr${i % 2 ? ' class="z"' : ''}>
        <td class="item">${esc(r[0])}</td>
        <td class="spec">${esc(spec(r[1]))}</td>
        <td class="holes">${holes(r[2])}</td>
        <td class="ang">${ang(r[3])}</td>
      </tr>`).join('');
  return `
  <table class="spec-table">
    <thead>
      <tr class="plate"><th colspan="4">${esc(opts.plate)}</th></tr>
      <tr class="head">
        <th class="item">Обозначение изделия</th>
        <th class="spec">Размеры D×H<span class="u">мм</span></th>
        <th class="holes">Диаметр отверстия d<span class="u">мм</span></th>
        <th class="ang">${angH}<span class="u">град.</span></th>
      </tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>`;
}

// ─── стр. 05: марки сплава ───────────────────────────────────────────────
function gradeTable() {
  const t = tbl('grade-list');
  const NEW = new Set(t.newBadge);
  const rows = t.rows.map((r, i) => {
    const grain = /j/.test(r[5])
      ? `<span class="flag" title="разделитель диапазона не читается в исходнике, см. TODO-01/02">${esc(dec(r[5].replace('j', ' ? ')))}</span>`
      : esc(dec(r[5]));
    const firstOfSeries = i === 0 || t.rows[i - 1][0] !== r[0];
    return `
      <tr${i % 2 ? ' class="z"' : ''}>
        <td class="ser s-${r[0]}">${firstOfSeries ? r[0] : ''}</td>
        <td class="item">${esc(r[1])}${NEW.has(r[1]) ? '<span class="new">новая</span>' : ''}</td>
        <td class="num">${esc(dec(r[2]).replace('~', '–'))}</td>
        <td class="num">${esc(dec(r[3]).replace('~', '–'))}</td>
        <td class="num">${esc(r[4])}</td>
        <td class="num">${grain}</td>
        <td class="app">${esc(APP[r[1]])}</td>
      </tr>`;
  }).join('');
  return `
  <table class="spec-table grade">
    <thead>
      <tr class="plate"><th colspan="7">Марки твёрдого сплава</th></tr>
      <tr class="head">
        <th class="ser">Серия</th>
        <th class="item">Марка</th>
        <th class="num">Твёрдость<span class="u">HRA</span></th>
        <th class="num">Плотность<span class="u">г/см³</span></th>
        <th class="num">Предел прочности при изгибе<span class="u">Н/мм²</span></th>
        <th class="num">Зернистость<span class="u">мкм</span></th>
        <th class="app">Рекомендуемое применение</th>
      </tr>
    </thead>
    <tbody>${rows}</tbody>
  </table>`;
}

