let total = 0;
for (const [file, edits] of Object.entries(jobs)) {
  let src = readFileSync(file, 'utf8');
  for (const [from, to, expect = 1] of edits) {
    const n = src.split(from).length - 1;
    if (n !== expect) {
      console.error(`ОШИБКА в ${file}: «${from.slice(0, 60)}…» найдено ${n} раз, ожидалось ${expect}`);
      process.exit(1);
    }
    src = src.split(from).join(to);
    total += n;
  }
  writeFileSync(file, src, 'utf8');
  console.log(`${file}: заменено ${edits.reduce((s, e) => s + (e[2] ?? 1), 0)} вхождений`);
}
console.log(`всего замен: ${total}`);
